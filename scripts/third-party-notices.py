"""Writes THIRD_PARTY_NOTICES.md: every crate the firmware and the app are built from (normal and
build dependencies, for the target each one runs on), with its licence, plus the bundled fonts.

Run from the repository root:  python scripts/third-party-notices.py
Needs only cargo and Python 3. Exits 1 if a licence falls outside the permissive set below.
"""
import json
import re
import subprocess
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
OUT = ROOT / "THIRD_PARTY_NOTICES.md"
CRATES = [("firmware", "thumbv7m-none-eabi"), ("app", "x86_64-pc-windows-msvc")]
PERMISSIVE = {
    "MIT", "MIT-0", "Apache-2.0", "Apache-2.0 WITH LLVM-exception", "BSD-2-Clause", "BSD-3-Clause",
    "0BSD", "ISC", "Zlib", "Unicode-3.0", "Unicode-DFS-2016",
}
FONTS = [
    ("firmware/assets/fonts/OpenSans-ExtraBold.ttf, OpenSans-SemiBold.ttf",
     "Open Sans, Copyright 2020 The Open Sans Project Authors (https://github.com/googlefonts/opensans)",
     "SIL Open Font License 1.1, full text in firmware/assets/fonts/OFL.txt. The logo and big font "
     "bitmaps in firmware/src/assets.rs are rendered from these files."),
    ("firmware/assets/fonts/5x7.bdf",
     "X11 misc-fixed 5x7 (via https://github.com/embedded-graphics/embedded-graphics)",
     "Public domain (\"Public domain font. Share and enjoy.\", in the file's COPYRIGHT property). "
     "firmware/src/font.rs is generated from it."),
]


def allowed(expr):
    """Evaluates an SPDX expression: true if the crate can be used under permissive terms only."""
    tokens = re.findall(r"\(|\)|[^\s()]+(?:\s+WITH\s+[^\s()]+)?", expr.replace("/", " OR "))
    pos = 0

    def atom():
        nonlocal pos
        tok = tokens[pos]
        pos += 1
        if tok == "(":
            v = any_of()
            pos += 1  # ")"
            return v
        return re.sub(r"\s+", " ", tok).removesuffix("+") in PERMISSIVE

    def all_of():
        nonlocal pos
        v = atom()
        while pos < len(tokens) and tokens[pos] == "AND":
            pos += 1
            v = atom() and v
        return v

    def any_of():
        nonlocal pos
        v = all_of()
        while pos < len(tokens) and tokens[pos] == "OR":
            pos += 1
            v = all_of() or v
        return v

    return any_of()


def crates(path, target):
    meta = json.loads(subprocess.check_output(
        ["cargo", "metadata", "--format-version", "1", "--locked", "--filter-platform", target],
        cwd=ROOT / path))
    packages = {p["id"]: p for p in meta["packages"]}
    nodes = {n["id"]: n for n in meta["resolve"]["nodes"]}
    seen, todo = set(), [meta["resolve"]["root"]]
    while todo:
        node = nodes[todo.pop()]
        for dep in node["deps"]:
            kinds = {k["kind"] for k in dep["dep_kinds"]}
            if kinds - {"dev"} and dep["pkg"] not in seen:
                seen.add(dep["pkg"])
                todo.append(dep["pkg"])
    out = []
    for pid in seen:
        p = packages[pid]
        if p["source"] is None:
            continue  # this repository's own crates
        out.append((p["name"], p["version"], p["license"] or "(none given)", p.get("repository") or ""))
    return sorted(out)


def main():
    lines = [
        "<!-- Generated by scripts/third-party-notices.py - do not edit. Regenerate with:",
        "     python scripts/third-party-notices.py -->",
        "",
        "# Third-party notices",
        "",
        "kb16-mixer itself is MIT licensed (see LICENSE). It is built from the crates below, each under",
        "its own licence, and ships bitmaps rendered from the fonts listed at the end.",
        "",
    ]
    flagged = []
    for path, target in CRATES:
        rows = crates(path, target)
        lines += [f"## {path} ({target}, {len(rows)} crates)", "", "| Crate | Version | Licence | Source |",
                  "|---|---|---|---|"]
        for name, version, lic, repo in rows:
            ok = lic != "(none given)" and allowed(lic)
            if not ok:
                flagged.append(f"{path}: {name} {version} ({lic})")
            lines.append(f"| {name} | {version} | {lic}{'' if ok else ' **(check)**'} | {repo} |")
        lines.append("")
    lines += ["## Fonts", ""]
    for files, what, lic in FONTS:
        lines += [f"- `{files}`: {what}. {lic}"]
    lines += ["", "## Licences outside MIT / Apache-2.0 / BSD / ISC / Zlib / Unicode", ""]
    lines += [f"- {f}" for f in flagged] or ["None."]
    OUT.write_text("\n".join(lines) + "\n", encoding="utf-8", newline="\n")
    print(f"wrote {OUT.name}; flagged: {flagged or 'none'}")
    sys.exit(1 if flagged else 0)


main()
